class _SDelegate extends LocalizationsDelegate<S> {
  const _SDelegate();

  @override
  bool isSupported(Locale locale) =>
      kLanguageCodes.contains(locale.languageCode);

  /// SynchronousFuture, not `async`.
  ///
  /// `Localizations.override` — which is how the per-section language switch
  /// works — renders an empty frame if any delegate returns a real Future.
  /// An `async` method always does, even when its body does no awaiting, so
  /// `async` here made every section language change flash blank.
  @override
  Future<S> load(Locale locale) => SynchronousFuture<S>(S(locale));

  @override
  bool shouldReload(_SDelegate old) => false;
}

